module Hephaestux.Agents
  ( AgentSpec (..),
    allAgents,
    lookupAgent,
    agentNames,
    symbolFor,
    labelFor,
  )
where

import Control.Applicative ((<|>))
import Data.Maybe (fromMaybe)
import Data.Text (Text)
import Hephaestux.Types (Agent (..))
import qualified Data.Text as Text
import Hephaestux.Install (InstallStep (..))

data AgentSpec = AgentSpec
  { specName :: Text,
    symbol :: Text,
    procNames :: [Text],
    plan :: [InstallStep],
    notes :: [Text]
  }

-- | Registry of the 10 supported agents.
allAgents :: [AgentSpec]
allAgents =
  [ ompSpec,
    piSpec,
    claudeSpec,
    codexSpec,
    opencodeSpec,
    antigravitySpec,
    kimiSpec,
    qwenSpec,
    clineSpec,
    deepseekSpec
  ]

lookupAgent :: Text -> Maybe AgentSpec
lookupAgent n = case filter ((== n) . (.specName)) allAgents of
  (a : _) -> Just a
  [] -> Nothing

-- | Symbol registered for an agent name; Nothing when the name is unknown.
symbolFor :: Text -> Maybe Text
symbolFor n = (.symbol) <$> lookupAgent n

-- | Display symbol for an agent: explicit, else the registry symbol, else the name.
labelFor :: Agent -> Text
labelFor a = fromMaybe a.name (a.symbol <|> symbolFor a.name)

agentNames :: [Text]
agentNames = map (.specName) allAgents

