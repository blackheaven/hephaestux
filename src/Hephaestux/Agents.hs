-- | Shared TS hook factory body for omp and pi (same extension API).
tsFactory :: Text -> Text
tsFactory agent =
  "// Generated by hephaestux setup; safe to regenerate.\n\
  \export default function (pi: any) {\n\
  \  const call = async (state: string, title: string | undefined) => {\n\
  \    const args = [\"update\", \"--agent\", \""
    <> agent
    <> "\", \"--state\", state];\n\
       \    if (title) args.push(\"--title\", title);\n\
       \    try {\n\
       \      await pi.exec(\"hephaestux\", args);\n\
       \    } catch {\n\
       \      // never break the agent\n\
       \    }\n\
       \  };\n\
       \  pi.on(\"session_start\", () => { void call(\"stale\", undefined); });\n\
       \  pi.on(\"agent_start\", () => { void call(\"working\", undefined); });\n\
       \  pi.on(\"agent_end\", () => { void call(\"waiting-input\", undefined); });\n\
       \  pi.on(\"session_shutdown\", () => {\n\
       \    try {\n\
       \      void pi.exec(\"hephaestux\", [\"end\"]);\n\
       \    } catch {\n\
       \      // never break the agent\n\
       \    }\n\
       \  });\n\
       \}\n"

