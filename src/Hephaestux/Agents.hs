-- | Claude-shape hooks config: an OBJECT keyed by event (official schema):
-- SessionStart -> stale, UserPromptSubmit -> working, Stop -> waiting-input,
-- SessionEnd -> end (timeout 3 on codex).
claudeHooks :: Text -> Text
claudeHooks agent =
  "{\n"
    <> updateEntry agent "stale"
    <> updateEntry agent "working"
    <> updateEntry agent "waiting-input"
    <> endEntry (Just 3)
    <> "}\n"

updateEntry :: Text -> Text -> Text
updateEntry agent state =
  "  \""
    <> eventFor state
    <> "\": [{ \"hooks\": [{ \"type\": \"command\", \"command\": \"hephaestux update --agent "
    <> agent
    <> " --state "
    <> state
    <> " || true\" }]}],\n"

eventFor :: Text -> Text
eventFor = \case
  "stale" -> "SessionStart"
  "working" -> "UserPromptSubmit"
  "waiting-input" -> "Stop"
  _ -> "SessionEnd"

endEntry :: Maybe Int -> Text
endEntry mtimeout =
  "  \"SessionEnd\": [{ \"hooks\": [{ \"type\": \"command\", \"command\": \"hephaestux end || true\""
    <> maybe "" (\t -> ", \"timeout\": " <> Text.pack (show t)) mtimeout
    <> " }]}]\n"

