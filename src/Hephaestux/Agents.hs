opencodePlugin :: Text
opencodePlugin =
  "// Generated by hephaestux setup; safe to regenerate.\n\
  \import type { Plugin } from \"@opencode-ai/plugin\";\n\
  \\n\
  \const update = async (state: string) => {\n\
  \  try {\n\
  \    const proc = Bun.spawn([\"hephaestux\", \"update\", \"--agent\", \"opencode\", \"--state\", state], { stdout: \"ignore\", stderr: \"ignore\" });\n\
  \    await proc.exited;\n\
  \  } catch {\n\
  \    // never break the agent\n\
  \  }\n\
  \};\n\
  \\n\
  \export const HephaestuxPlugin: Plugin = async () => ({\n\
  \  event: async ({ event }) => {\n\
  \    if (event.type === \"session.created\") await update(\"stale\");\n\
  \    if (event.type === \"chat.message\") await update(\"working\");\n\
  \    if (event.type === \"session.idle\") await update(\"waiting-input\");\n\
  \    if (event.type === \"session.deleted\") {\n\
  \      try {\n\
  \        const proc = Bun.spawn([\"hephaestux\", \"end\"], { stdout: \"ignore\", stderr: \"ignore\" });\n\
  \        await proc.exited;\n\
  \      } catch {\n\
  \        // never break the agent\n\
  \      }\n\
  \    }\n\
  \  },\n\
  \});\n\
  \\n\
  \export default HephaestuxPlugin;\n"

