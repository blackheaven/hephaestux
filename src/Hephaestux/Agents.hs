-- | Claude-shape hooks without SessionEnd (deepseek has no such event).
claudeHooksNoEnd :: Text -> Text
claudeHooksNoEnd agent =
  "{\n"
    <> updateEntry agent "stale"
    <> updateEntry agent "working"
    <> "  \"Stop\": [{ \"hooks\": [{ \"type\": \"command\", \"command\": \"hephaestux update --agent "
    <> agent
    <> " --state waiting-input || true\" }]}]\n\
       \}\n"

deepseekOverlay :: Text
deepseekOverlay =
